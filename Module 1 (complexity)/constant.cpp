#include<bits/stdc++.h>
using namespace std;

int main()
    {
        int n, m; // O(1)
        cin >> n >> m; // O(1)

        int total = n + m; // O(1)

        cout << total; // O(1)
        return 0; // O(1)
    } 

    /*
    -> Everytime this programme completing only ONE operations;
    -> Whatever n or m is. It will complete only ONE operations;
    -> So, Time complexity is = O(1);
    */